/*
Package fingerprinters provides HTTP fingerprinting for the Microsoft .NET
Remoting HTTP channel (System.Runtime.Remoting.Channels.Http.HttpChannel).

Detection is passive and header-only: the standalone channel stamps every
response — including GET / — with the framework banner
"MS .NET Remoting, MS .NET CLR <version>", which is generated by
HttpServerTransportSink and not controllable by application code. The
response body is never inspected.

The channel performs no authentication or type filtering: an attacker who
finds a valid object URI gets unauthenticated deserialization RCE, which is
why every detection attaches the High-severity finding
"dotnet-remoting-http-exposed" (emitted only under --misconfigs).

Not detected: remoting endpoints behind a proxy that strips the Server
header, IIS/ASP.NET-hosted remoting (IIS replaces the banner), and the TCP
channel.
*/
package fingerprinters

import (
	"fmt"
	"net/http"
	"regexp"
	"strings"

	"github.com/praetorian-inc/nerva/pkg/plugins"
)

// dotNetRemotingServerMarker is the lowercase framework banner set by
// HttpServerTransportSink on every channel response.
const dotNetRemotingServerMarker = "ms .net remoting"

// dotNetRemotingCLRRegex extracts the CLR engine version from the Server
// header. The capture class cannot capture CPE metacharacters.
var dotNetRemotingCLRRegex = regexp.MustCompile(`(?i)ms\s*\.net\s*clr\s+([0-9]+(?:\.[0-9]+){1,3})`)

func init() {
	Register(&DotNetRemotingFingerprinter{})
}

// DotNetRemotingFingerprinter detects the standalone .NET Remoting HTTP
// channel. It is passive by design: it implements only HTTPFingerprinter
// and declares no ProbeEndpoint, so the engine's passive pass evaluates it
// against the already-fetched root response.
type DotNetRemotingFingerprinter struct{}

// Name returns the fingerprinter identifier.
func (f *DotNetRemotingFingerprinter) Name() string { return "dotnet-remoting-http" }

// Match reports whether the response carries the framework's remoting banner.
func (f *DotNetRemotingFingerprinter) Match(resp *http.Response) bool {
	return strings.Contains(strings.ToLower(resp.Header.Get("Server")), dotNetRemotingServerMarker)
}

// Fingerprint confirms a .NET Remoting HTTP channel via the Server header
// banner and extracts CLR and framework version metadata. The body is not
// inspected.
func (f *DotNetRemotingFingerprinter) Fingerprint(resp *http.Response, body []byte) (*FingerprintResult, error) {
	serverHeader := resp.Header.Get("Server")
	if !f.Match(resp) {
		return nil, nil
	}

	metadata := map[string]any{
		"detection_method": "server_header",
	}

	var clrVersion string
	if m := dotNetRemotingCLRRegex.FindStringSubmatch(serverHeader); len(m) > 1 {
		clrVersion = m[1]
		metadata["clr_version"] = clrVersion
	}
	frameworkVersion, exact := dotNetCLRToFramework(clrVersion)
	if frameworkVersion != "" {
		metadata["framework_version"] = frameworkVersion
	}

	// Ambiguous CLR builds are wildcarded in the CPE; an imprecise version
	// would silently break CVE correlation.
	version := ""
	if exact {
		version = frameworkVersion
	}

	evidence := fmt.Sprintf("Server header advertises .NET Remoting channel: %q", serverHeader)

	return &FingerprintResult{
		Technology: "dotnet-remoting-http",
		Version:    version,
		CPEs:       []string{buildDotNetFrameworkCPE(version)},
		Metadata:   metadata,
		SecurityFindings: []plugins.SecurityFinding{{
			ID:          "dotnet-remoting-http-exposed",
			Severity:    plugins.SeverityHigh,
			Description: ".NET Remoting HTTP channel exposed (unauthenticated deserialization risk once a valid object URI is found)",
			Evidence:    evidence,
		}},
	}, nil
}

// dotNetCLRToFramework maps a CLR engine version to the .NET Framework
// release(s) it corresponds to. Most CLR builds are shared by several
// Framework releases; the bool reports whether the mapping is exact.
func dotNetCLRToFramework(clr string) (string, bool) {
	switch {
	case clr == "":
		return "", false
	case strings.HasPrefix(clr, "2.0.50727"):
		return "2.0-3.5", false // CLR 2.0 underlies .NET 2.0, 3.0 and 3.5.
	case strings.HasPrefix(clr, "4.0.30319."):
		switch clr {
		case "4.0.30319.18000":
			return "4.5", true
		case "4.0.30319.18400":
			return "4.5.1", true
		case "4.0.30319.19000":
			return "4.5.2", true
		case "4.0.30319.42000":
			return "4.6-4.8.1", false // every Framework from 4.6 through 4.8.1
		}
		return "4.x", false // 4.0 RTM and patched 4.0.x builds: series only.
	default:
		return "", false
	}
}

// buildDotNetFrameworkCPE constructs the CPE 2.3 identifier for the .NET
// Framework that provides the remoting channel. .NET Remoting has no CPE
// product of its own; framework CVEs apply to the channel.
func buildDotNetFrameworkCPE(version string) string {
	if version == "" || strings.ContainsAny(version, ":*?") {
		return "cpe:2.3:a:microsoft:.net_framework:*:*:*:*:*:*:*:*"
	}
	return fmt.Sprintf("cpe:2.3:a:microsoft:.net_framework:%s:*:*:*:*:*:*:*", version)
}
